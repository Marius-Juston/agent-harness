"""Generated references (`uv run dev docs`). Never hand-edit the outputs; the gate fails when they are stale.

- <generated_dir>/agent-surface.md: agents, skills, hooks, plugins, MCP servers, dev commands and budgets, derived
  from the files that define them, so prose never has to repeat a count, a field or a command list.
- <research_dir>/INDEX.md: every research note with its status and one-line finding, so agents check what is
  already researched before starting (duplicate research is the most common research waste).
- <generated_dir>/decisions.md: the decision table (`[tool.devkit] decisions`), written even without one.
  Linked, never @-imported, so it costs no agent context until opened.
- the copies `[tool.devkit] action_pins` names: their action pins follow their source workflow (#431), so a
  Dependabot bump of the source alone is completed by `dev docs`, which integrate runs on the merged tree.
"""

import json
import posixpath
import re
import tomllib
from collections.abc import Sequence

from devkit import config, frontmatter
from devkit.checks import _agents, _hook_files, _kind, _skills, decision_rows, measured_words
from devkit.paths import root

HEADER = "<!-- Generated by `uv run dev docs`. Do not edit by hand. -->\n"


def _first_sentence(text: str, cap: int = 160) -> str:
    text = " ".join(str(text).split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    return s if len(s) <= cap else s[: cap - 3] + "..."


def _cell(text: object) -> str:
    return str(text).replace("|", "/").replace("\n", " ")


def _rel(p) -> str:
    return str(p.relative_to(root()))


def _scoped(p, name: object) -> str:
    """The name Claude Code gives a component: `<plugin>:<name>` inside a plugin, bare in a project."""
    for s in config.get().surface:
        manifest = root() / s / ".claude-plugin/plugin.json"
        if manifest.exists() and p.is_relative_to(root() / s):
            return f"{json.loads(manifest.read_text()).get('name', s)}:{name}"
    return str(name)


def surface(commands: Sequence[tuple[str, str]]) -> str:
    """`commands` is the CLI's (name, help) rows, passed in because the CLI imports this module."""
    cfg = config.get()
    words = measured_words()
    budgets = tomllib.loads((root() / cfg.ratchets).read_text())
    roots = ", ".join(f"`{s}`" for s in cfg.surface)
    out = [HEADER, "# Agent surface (generated)\n"]
    out.append(
        f"## Subagents ({roots})\n\n| name | model | effort | tools | words | use when |\n|---|---|---|---|---|---|"
    )
    for p in _agents():
        meta, _ = frontmatter.read(p)
        meta = meta or {}
        tools = meta.get("tools", "all")
        out.append(
            f"| {_scoped(p, meta.get('name'))} | {meta.get('model', 'inherit')} | {meta.get('effort', '-')} | {_cell(tools)} | "
            f"{words.get(_rel(p), 0)} | {_cell(_first_sentence(meta.get('description', '')))} |"
        )
    out.append(f"\n## Skills ({roots})\n\n| name | invocation | words | purpose |\n|---|---|---|---|")
    for p in _skills():
        meta, _ = frontmatter.read(p)
        meta = meta or {}
        how = ("user only: /" if meta.get("disable-model-invocation") else "model + /") + _scoped(p, meta.get("name"))
        out.append(
            f"| {_scoped(p, meta.get('name'))} | {how} | {words.get(_rel(p), 0)} | "
            f"{_cell(_first_sentence(meta.get('description', '')))} |"
        )
    out.append("\n## Hooks\n\n| file | event | matcher | command |\n|---|---|---|---|")
    for name, _ in _hook_files():
        data = json.loads((root() / name).read_text())
        for event, groups in (data.get("hooks") or {}).items():
            for g in groups:
                for h in g.get("hooks", []):
                    cmd = " ".join([h.get("command", ""), *h.get("args", [])])
                    cmd = re.sub(r"\"?\$\{?CLAUDE_(?:PROJECT_DIR|PLUGIN_ROOT)\}?\"?/", "", cmd)
                    out.append(f"| {name} | {event} | {_cell(g.get('matcher', '*'))} | `{cmd}` |")
        for module in data.get("modules", []):
            out.append(f"| {name} | (mod) | - | `{module}` |")
    settings_file = root() / ".claude/settings.json"
    settings = json.loads(settings_file.read_text()) if settings_file.exists() else {}
    markets = settings.get("extraKnownMarketplaces") or {}
    out.append("\n## Plugins (`.claude/settings.json`)\n\n| plugin | enabled | marketplace source |\n|---|---|---|")
    for plugin, on in (settings.get("enabledPlugins") or {}).items():
        src = (markets.get(plugin.partition("@")[2]) or {}).get("source") or {}
        where = "@".join(x for x in (src.get("repo") or src.get("path") or src.get("url") or "", src.get("ref")) if x)
        out.append(f"| {plugin} | {on} | {_cell(where or '-')} |")
    mcp = json.loads((root() / ".mcp.json").read_text()) if (root() / ".mcp.json").exists() else {}
    out.append("\n## MCP servers (`.mcp.json`)\n\n| server | command |\n|---|---|")
    for name, spec in (mcp.get("mcpServers") or {}).items():
        out.append(
            f"| {name} | `{_cell(' '.join([spec.get('command', spec.get('url', '')), *spec.get('args', [])]))}` |"
        )
    out.append("\n## Dev commands (`uv run dev <command>`)\n\n| command | what |\n|---|---|")
    out += [f"| `{name}` | {_cell(text)} |" for name, text in commands]
    out.append(f"\n## Word budgets (`{cfg.ratchets}`, only tighten)\n\n| file | words | budget |\n|---|---|---|")
    for rel, n in sorted(words.items()):
        default = budgets.get("defaults", {}).get(_kind(rel), "-")
        out.append(f"| {rel} | {n} | {budgets.get('words', {}).get(rel, default)} |")
    return "\n".join(out) + "\n"


def research_index() -> str:
    out = [
        HEADER,
        "# Research index (generated)\n",
        "Read this before researching: extend an existing note rather than writing a parallel one.\n",
        "| note | status | finding |",
        "|---|---|---|",
    ]
    for p in sorted((root() / config.get().research_dir).glob("*.md")):
        if p.name in {"INDEX.md", "README.md"}:
            continue
        text = p.read_text(encoding="utf-8")
        title = re.match(r"# Research: (.+)", text)
        status = re.search(r"^Status: (.+)$", text, re.M)
        finding = re.search(r"## 0\.?[^\n]*\n+(.+?)(?:\n\n|\n#)", text, re.S)
        out.append(
            f"| [{_cell(title.group(1) if title else p.stem)}]({p.name}) | {_cell(status.group(1) if status else '?')} | "
            f"{_cell(_first_sentence(finding.group(1), 220) if finding else '')} |"
        )
    return "\n".join(out) + "\n"


def decisions_index() -> str:
    """The decision table as a page. Always written, so the template-owned HARNESS.md link resolves even in a project
    that deleted its table; the page then names no file, because a link to a missing one fails the link check."""
    cfg = config.get()
    try:
        text = (root() / cfg.decisions).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        text = None
    rows = decision_rows(text)[1] if text is not None else []
    source = f"[{cfg.decisions}]({posixpath.relpath(cfg.decisions, cfg.generated_dir)})" if text is not None else None
    out = [
        HEADER,
        "# Decisions (generated)\n",
        f"Durable rules from {source}." if source else "Durable rules from the table `[tool.devkit] decisions` names.",
        "`uv run dev check` warns when an active row's literal leaves its path; a PR that changes such a rule",
        "supersedes its row.\n",
    ]
    if not rows:
        return "\n".join([*out, "No decisions recorded.\n"])
    out += ["| id | rule | status | why | enforced by |", "|---|---|---|---|---|"]
    for r in rows:
        status = f"{r.get('status', '?')} by {r['by']}" if r.get("by") else str(r.get("status", "?"))
        marks = r.get("enforced-by") if isinstance(r.get("enforced-by"), list) else []
        held = "; ".join(f"`{m.get('literal')}` in {m.get('path')}" for m in marks if isinstance(m, dict))
        out.append(
            f"| {_cell(r.get('id', '?'))} | {_cell(r.get('rule', ''))} | {_cell(status)} | {_cell(r.get('why', ''))} |"
            f" {_cell(held)} |"
        )
    return "\n".join(out) + "\n"


# A step's commit-pinned action, as Dependabot writes it: `uses: owner/repo[/path]@<sha> # <version> [more words]`.
USES = re.compile(
    r"(?P<head>\buses:[ \t]*[\"']?)(?P<action>[\w.-]+/[\w./-]+)@(?P<sha>[0-9a-f]{40})(?P<quote>[\"']?)"
    r"(?:(?P<hash>[ \t]*#[ \t]*)(?P<version>[^\s#]+))?"
)


def synced_pins(source: str, mirror: str) -> str:
    """`mirror` with each action `source` pins to one commit moved to that commit and its version comment (later
    words of the comment kept). An action `source` does not use, pins two ways, or pins to the commit `mirror`
    already has, is left as it is."""
    pins: dict[str, set[tuple[str, str | None]]] = {}
    for m in USES.finditer(source):
        pins.setdefault(m["action"], set()).add((m["sha"], m["version"]))

    def repin(m: re.Match) -> str:
        if len(pins.get(m["action"], ())) != 1:
            return m[0]
        ((sha, version),) = pins[m["action"]]
        if sha == m["sha"]:  # one commit: its label may be more precise here (`# v7.0.1` against `# v7`)
            return m[0]
        comment = m["hash"] + (version or m["version"]) if m["version"] else f" # {version}" if version else ""
        return f"{m['head']}{m['action']}@{sha}{m['quote']}{comment}"

    return USES.sub(repin, mirror)


def pinned_mirrors(tree, action_pins: dict[str, list[str]]) -> dict[str, str]:
    """Copy path -> its text with the pins of its source workflow (`[tool.devkit] action_pins`), for each file the
    globs match under `tree`. Raises ConfigError when a source is missing: a typo must not pass as nothing to sync."""
    out = {}
    for source, globs in action_pins.items():
        if not (tree / source).is_file():
            raise config.ConfigError(f"[tool.devkit.action_pins]: {source} does not exist")
        text = (tree / source).read_text(encoding="utf-8")
        for path in sorted({p for g in globs for p in tree.glob(g) if p.is_file()}):
            if (rel := path.relative_to(tree).as_posix()) != source:
                out[rel] = synced_pins(text, path.read_text(encoding="utf-8"))
    return out


def render(commands: Sequence[tuple[str, str]]) -> dict[str, str]:
    cfg = config.get()
    return {
        f"{cfg.generated_dir}/agent-surface.md": surface(commands),
        f"{cfg.research_dir}/INDEX.md": research_index(),
        f"{cfg.generated_dir}/decisions.md": decisions_index(),
        **pinned_mirrors(root(), cfg.action_pins),
    }


def write(commands: Sequence[tuple[str, str]]) -> list[str]:
    changed = []
    for rel, content in render(commands).items():
        path = root() / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
            changed.append(rel)
    return changed
